export const carTypes = ["Sedan", "SUV", "Wagon", "Sports", "Luxury", "Electric"];

export const brands = [...new Set(cars.map((car) => car.brand))].sort();

export const featuredCars = cars.filter((car) => car.featured);

export const popularCars = cars.filter((car) => car.popular && !car.featured);

export function getLocation(id) {
  return locations.find((location) => location.id === id) || null;
}

export function locationGroups() {
  const groups = new Map();
  for (const location of locations) {
    if (!groups.has(location.city)) groups.set(location.city, []);
    groups.get(location.city).push(location);
  }
  return [...groups.entries()];
}

export function getCar(id) {
  return cars.find((car) => car.id === id) || null;
}

export function getSimilar(car, count = 3) {
  const related = cars.filter((item) => item.id !== car.id && item.available && item.type === car.type);
  const rest = cars.filter((item) => item.id !== car.id && item.available && item.type !== car.type);
  return [...related, ...rest].slice(0, count);
}

export function lowestDaily() {
  return Math.min(...cars.map((car) => car.daily));
}
